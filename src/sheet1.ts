import XLSX from "xlsx";

interface AdditionalData {
  [key: string]: string;
}

interface JsonData {
  sheetName: string;
  additionalData?: AdditionalData;
  rows: any[];
}

function flattenData(data: any[]): any[][] {
  const flattenedData: any[][] = [];

  function flatten(obj: any, prefix = "") {
    for (const key in obj) {
      if (typeof obj[key] === "object" && obj[key] !== null) {
        flatten(obj[key], prefix + key + ".");
      } else {
        flattenedData.push([prefix + key, obj[key]]);
      }
    }
  }

  data.forEach((item) => flatten(item));
  return flattenedData;
}

function createExcelSheet(data: JsonData) {
  // Create a new workbook
  const workbook = XLSX.utils.book_new();

  // Convert the JSON data to a worksheet
  const worksheet = XLSX.utils.aoa_to_sheet(flattenData(data.rows));

  // Adjust column widths based on the length of the data
  const columnWidths: { [key: string]: number } = {};
  for (const cell in worksheet) {
    if (!cell.toString()[0].startsWith("!")) {
      const columnName = cell.toString().replace(/[0-9]/g, "");
      const cellValue = worksheet[cell].v;
      let cellWidth = 0;

      if (typeof cellValue === "string") {
        cellWidth = cellValue.length;
      } else if (typeof cellValue === "number") {
        cellWidth = cellValue.toString().length;
      } else if (cellValue instanceof Date) {
        cellWidth = cellValue.toLocaleString().length;
      }

      columnWidths[columnName] = Math.max(
        columnWidths[columnName] || 0,
        cellWidth
      );
    }
  }

  worksheet["!cols"] = Object.keys(columnWidths).map((column) => ({
    wch: columnWidths[column],
  }));

  // Add additional data to the worksheet

  // Add the worksheet to the workbook
  XLSX.utils.book_append_sheet(workbook, worksheet, data.sheetName);
  console.log(workbook);
  // Write the workbook to a file
  XLSX.writeFile(workbook, "output.xlsx");
}

